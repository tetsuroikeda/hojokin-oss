def test_shapes_that_differ_between_programs() -> None:
    """両制度で形が分かれる所を、それぞれの例が持っている。"""
    s, j = shoryokuka_8(), jizokuka_20()
    # 日の決まっていない期日
    assert any("年月" in d["日時"]["値"] for d in s["決まった期日"])
    # 期限の決め方の4種類
    kinds = {x["種類"] for x in walk([s["手続きの段階"], j["手続きの段階"]]) if isinstance(x, dict) and "種類" in x and ("期間" in x or "日時" in x or "期限" in x or "回数" in x)}
    assert kinds == {"決まった日付", "出来事からの期間", "早いほう", "繰り返し"}
    # 特例の種類（上限の置き換えと上乗せ）
    assert {t["種類"] for t in s["補助額"][0]["特例"]} >= {"上限の置き換え"}
    assert {t["種類"] for t in j["補助額"][0]["特例"]} >= {"上限の上乗せ"}
    # 様式の入力先（ファイルと画面）
    assert {f["入力先"]["値"]["種類"] for f in s["様式"]} == {"ファイル"}
    assert {f["入力先"]["値"]["種類"] for f in j["様式"]} == {"画面"}
    # 案件と回の違う資料
    for data in (s, j):
        assert any(d["公募回"] != data["制度"]["公募回"] for d in data["資料"])
    # 印刷された番号と PDF のページのずれ
    assert {d.get("ページのずれ") for d in j["資料"]} >= {1, 5}
    # 読み取れない値
    assert s["加点"]["区分ごとの上限"]["状態"] == "読み取れない"
    # 経費の上限の形（総額に対する割合と、補助金額の上限）
    assert any("割合" in e["上限"]["値"] for e in s["補助の対象にならない経費"] if e["種類"] == "上限")
    assert any(e["上限"]["値"]["何の上限"] == "補助金額" for e in j["補助の対象にならない経費"] if e["種類"] == "上限")
    # 数値でない要件の2つの種類（満たすことと、当たらないこと）
    for data in (s, j):
        assert {r["種類"] for r in data["数値でない要件"]} == {"満たすこと", "当たらないこと"}


