def period(event: str, n: int, unit: str) -> dict:
    return {"種類": "出来事からの期間", "出来事": event, "期間": {"数": n, "単位": unit}}


def fixed(when: str) -> dict:
    return {"種類": "決まった日付", "日時": when}


